#!/usr/bin/env python3
"""Generate src/doors/doors_consts.h from the mint (spec 4.5).

The tool needs to know which door index is the real chamber; that index
is mint-derived (spec 4.0) and nothing else about the doors is compiled
in.

usage: gen_consts.py            (writes src/doors/doors_consts.h)
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "src", "gen"))
import mint  # noqa: E402

TEMPLATE = """#ifndef PRAMBH_DOORS_CONSTS_H
#define PRAMBH_DOORS_CONSTS_H

/* generated by src/doors/gen_consts.py from the minted seed
 * SHA256("prambh:doors:real:v1") (spec 4.5). */
#define PRAMBH_REAL_DOOR_INDEX %d

#endif
"""


def main():
    path = os.path.join(ROOT, "src", "doors", "doors_consts.h")
    with open(path, "w") as f:
        f.write(TEMPLATE % mint.real_door_index())
    print("wrote %s (real door index %d)" % (path, mint.real_door_index()))


if __name__ == "__main__":
    main()
