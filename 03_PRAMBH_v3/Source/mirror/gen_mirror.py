#!/usr/bin/env python3
"""Mirror Room generator (spec 4.6) - organizer-side.

Writes:
  src/mirror/mirror_consts.h   the Duplicate Survey's own constants: its
                               milestone token, its stage-A load vector,
                               the mirror chain dials, and SHA-256 of the
                               one filed title mirror_validate accepts
  <pkgdir>/mirror/*.txt        the Duplicate Survey fiction (generated,
                               never hand-written), dated 1981 and citing
                               plate ids that do not exist in plates/
  organizer-private/runs/p7_mirror_gen.txt

The chain values come from organizer-private/runs/mirror_chain.txt
(harvested, never recomputed here).

usage: gen_mirror.py <pkgdir>
"""
import hashlib
import json
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "src", "gen"))
import mint  # noqa: E402

PARAMS = json.load(open(os.path.join(ROOT, "src", "chain", "chain_params.json")))
S = PARAMS["table_bytes"]
T = PARAMS["budgets"]["mirror"]["T"]
RUNS = os.path.join(ROOT, "organizer-private", "runs")
CONSTS = """#ifndef PRAMBH_MIRROR_CONSTS_H
#define PRAMBH_MIRROR_CONSTS_H

/* generated by src/mirror/gen_mirror.py - the Duplicate Survey's own
 * constants (spec 4.6).  Nothing here is a real value. */
#define MIRROR_MILESTONE_TOKEN "%(token)s"
#define MIRROR_TABLE_BYTES %(s)d
#define MIRROR_STEPS %(t)d

static const unsigned char MIRROR_TITLE_DIGEST[32] = {
%(digest)s
};

#endif
"""


def harvest():
    path = os.path.join(RUNS, "mirror_chain.txt")
    if not os.path.exists(path):
        raise SystemExit("gen_mirror: %s missing - run mirror_chain.py first" % path)
    vals = {}
    for line in open(path):
        if line.startswith("stage A out"):
            vals["a"] = line.split("=")[1].split()[0].strip()
        elif line.startswith("stage B out"):
            vals["b"] = line.split("=")[1].split()[0].strip()
        elif line.startswith("dead-end title"):
            vals["title"] = line.split("=")[1].strip()
    for k in ("a", "b", "title"):
        if k not in vals:
            raise SystemExit("gen_mirror: %s lacks %s" % (path, k))
    return vals


def fiction():
    """The Duplicate Survey's own folios: internally consistent, dated
    1981, and citing plate ids that do not exist in plates/."""
    label = "prambh:mirror:folio:v1"
    folios = []
    for i in range(6):
        tok = mint.sha256ctr(mint.seed(label, struct.pack("<Q", i)), 4).hex()
        phantom = 900 + mint.seed(label, b"phantom" + struct.pack("<Q", i))[0] % 99
        lines = ["THE DUPLICATE SURVEY - folio %03d-%02d / stitch %s"
                 % (100 + i * 7, i, tok),
                 "opened in the year 1981, a second pass for the valley depot.",
                 "the plates carried in this folio are numbered %s and %s."
                 % ("plate_%03d" % phantom, "plate_%03d" % (phantom + 1)),
                 "the first survey's own sheets were said to be a year later,",
                 "so the depot keeps this pass as the earlier record.",
                 "the loom for this pass was borrowed from the coast issue and",
                 "its stitch table was never returned to the depot.",
                 "operators are reminded that the duplicate pass is filed here,",
                 "not at the valley works, and that no other pass exists."]
        folios.append("\n".join(lines) + "\n")
    return folios


def main(argv):
    if len(argv) != 2:
        sys.stderr.write(__doc__)
        return 2
    pkgdir = argv[1]
    vals = harvest()
    title = vals["title"]
    digest = hashlib.sha256(title.encode()).digest()
    body = CONSTS % {
        "token": mint.mirror_milestone_token(),
        "vector": mint.mirror_stage_a_seed().hex(),
        "s": S, "t": T,
        "digest": "\n".join("    " + ", ".join("0x%02x" % b for b in digest[i:i + 8])
                            + "," for i in range(0, 32, 8)),
    }
    with open(os.path.join(ROOT, "src", "mirror", "mirror_consts.h"), "w") as f:
        f.write(body)
    outdir = os.path.join(pkgdir, "mirror")
    os.makedirs(outdir, exist_ok=True)
    for i, text in enumerate(fiction()):
        with open(os.path.join(outdir, "duplicate_%02d.txt" % i), "w") as f:
            f.write(text)
    rep = ["P7 - MIRROR ROOM GENERATED (spec 4.6)",
           "milestone token: %s" % mint.mirror_milestone_token(),
           "stage A vector: %s" % vals["a"],
           "stage B out: %s" % vals["b"],
           "filed title: %s" % title,
           "title digest: %s" % digest.hex(),
           "chain dials: S=%d T=%d" % (S, T),
           "fiction folios: %d (dated 1981, cite plate ids absent from plates/)"
           % len(fiction()),
           "real values in mirror/ : 0 (asserted by the P7 suite leak lane)"]
    with open(os.path.join(RUNS, "p7_mirror_gen.txt"), "w") as f:
        f.write("\n".join(rep) + "\n")
    print("\n".join(rep))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
