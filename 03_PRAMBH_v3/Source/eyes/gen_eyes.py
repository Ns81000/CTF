#!/usr/bin/env python3
"""Generate the eyes constants and the sealed viewing notes (spec 4.7).

  src/eyes/eyes_consts.h   chain #2 dials + SHA-256 of the assembled title
                           (the validator stores nothing else)
  <pkgdir>/stage5_eyes/eyes_notes.bin  the viewing instructions, XOR
                           SHA256ctr(K_eyes) where K_eyes is chain #2's
                           output (harvested from runs/chain2_walk.txt)

usage: gen_eyes.py <pkgdir>
"""
import hashlib
import json
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "src", "gen"))
import mint  # noqa: E402

RUNS = os.path.join(ROOT, "organizer-private", "runs")
NOTES_MAX = 2048
PACING_MS = 60000
PARAMS = json.load(open(os.path.join(ROOT, "src", "chain", "chain_params.json")))
S = PARAMS["table_bytes"]
T = PARAMS["budgets"]["chain2"]["T"]

CONSTS = """#ifndef PRAMBH_EYES_CONSTS_H
#define PRAMBH_EYES_CONSTS_H

/* generated by src/eyes/gen_eyes.py (spec 4.7): chain #2 dials and the
 * SHA-256 of the assembled title.  The validator stores only that. */
#define EYES_TABLE_BYTES %(s)d
#define EYES_STEPS %(t)d
#define EYES_PACING_MS %(pace)d
#define EYES_NOTES_MAX %(nmax)d

static const unsigned char EYES_TITLE_DIGEST[32] = {
%(digest)s
};

#endif
"""


def sha256ctr(key, n):
    out = bytearray()
    c = 0
    while len(out) < n:
        out += hashlib.sha256(key + struct.pack("<Q", c)).digest()
        c += 1
    return bytes(out[:n])


def xor(a, b):
    return bytes(x ^ y for x, y in zip(a, b))


def notes_text():
    c = [mint.eyes_code(i) for i in range(3)]
    lines = [
        "SURVEYOR'S EYES - viewing notes, first survey, valley issue",
        "",
        "three plates were cut for this survey.  read them in this order and",
        "take one six-glyph code from each.",
        "",
        "1. depth.png - the dot plate.  let your eyes settle until a plane",
        "   stands out with a nearer cut than the rest.  the survey's number",
        "   is the plane cut NEAREST; a deeper plane carries the depot's own",
        "   copy.  read the nearest plane.",
        "   the survey's number for this plate: %s" % c[0],
        "",
        "2. hue.png - the dot plate in colour.  hold it in plain daylight and",
        "   read the difference in HUE, not in brightness: the two hues are",
        "   matched in luminance, so a reading taken from brightness alone",
        "   belongs to the depot's copy.",
        "   the survey's number for this plate: %s" % c[1],
        "",
        "3. sheet_a.png and sheet_b.png - the line screens.  lay one over the",
        "   other and turn the pair to the survey bearing, %.1f degrees: the"
        % 11.0,
        "   fine bands resolve first and carry the survey's number.  the",
        "   coarse bands, which resolve at the reciprocal bearing, are the",
        "   depot's copy.  no printer is required; any viewer that can",
        "   overlap the two images serves.",
        "   the survey's number for this pair: %s" % c[2],
        "",
        "the three numbers are spoken in the order above, joined with a",
        "single underscore, and that string is the eyes ink.",
        "",
    ]
    return "\n".join(lines)


def chain2_out():
    for name in ("chain2_walk.txt",):
        path = os.path.join(RUNS, name)
        if os.path.exists(path):
            for line in open(path):
                if line.startswith("out="):
                    return line.split("=", 1)[1].strip()
    raise SystemExit("gen_eyes: runs/chain2_walk.txt missing - run "
                     "src/gen/chain_jobs.py eyes2 first")


def chain1_out():
    for name in ("chain1_walk.txt", "p5_chain1_raw.txt"):
        path = os.path.join(RUNS, name)
        if os.path.exists(path):
            for line in open(path):
                if line.startswith("out="):
                    return line.split("=", 1)[1].strip()
    raise SystemExit("gen_eyes: no chain #1 output found")


def main(argv):
    if len(argv) != 2:
        sys.stderr.write(__doc__)
        return 2
    pk = argv[1]
    out2 = chain2_out()
    out1 = chain1_out()
    title = mint.final_title(bytes.fromhex(out2), bytes.fromhex(out1))
    digest = mint.title_digest(title)
    with open(os.path.join(HERE, "eyes_consts.h"), "w") as f:
        f.write(CONSTS % {
            "s": S, "t": T, "pace": PACING_MS, "nmax": NOTES_MAX,
            "digest": "\n".join("    " + ", ".join("0x%02x" % b
                                                   for b in digest[i:i + 8]) + ","
                                for i in range(0, 32, 8)),
        })
    notes = notes_text().encode()
    plain = notes + bytes(NOTES_MAX - len(notes))
    outdir = os.path.join(pk, "stage5_eyes")
    os.makedirs(outdir, exist_ok=True)
    with open(os.path.join(outdir, "eyes_notes.bin"), "wb") as f:
        f.write(xor(plain, sha256ctr(bytes.fromhex(out2), NOTES_MAX)))
    rep = ["P8 - EYES GENERATED (spec 4.7)",
           "chain #2 out (K_eyes, seal source): %s" % out2,
           "seal ink: %s" % mint.seal_ink(bytes.fromhex(out2)),
           "eyes ink: %s" % mint.eyes_ink(),
           "door ink: %s" % mint.door_ink(),
           "FINAL TITLE: %s" % title,
           "title digest: %s" % digest.hex(),
           "eyes_notes.bin: %d bytes sealed with K_eyes" % NOTES_MAX,
           "chain dials: S=%d T=%d, pacing %d ms" % (S, T, PACING_MS),
           "PLATES: depth.png hue.png sheet_a.png sheet_b.png (plate_gen.py)"]
    with open(os.path.join(RUNS, "p8_eyes_build.txt"), "w") as f:
        f.write("\n".join(rep) + "\n")
    print("\n".join(rep))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))

