#!/usr/bin/env python3
"""Emit the organizer-side chain job script (spec 4.1 / Appendix B.2).

Every chain value the package needs is produced by ONE deterministic
command; this generator prints the whole script so any run (build
session, audit) reproduces the values bit-for-bit:

  loom1  chain #1 (the loom, production T) from the opened capsule
  eyes2  chain #2 (the eyes seal) from the real chamber's handover vector
  doors  the seven decoy-chamber walks (12 min budget each, spec 4.5)
  mirror the mirror campaign's two-stage chain (spec 4.6, its own driver)

Each job writes its own report into organizer-private/runs/ and records
its real elapsed seconds, so no timing is ever estimated by hand.

usage: chain_jobs.py [set ...]            (default: all)
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, HERE)
import mint  # noqa: E402

PARAMS = json.load(open(os.path.join(ROOT, "src", "chain", "chain_params.json")))
S = PARAMS["table_bytes"]
T1 = PARAMS["budgets"]["chain1"]["T"]
TDOOR = PARAMS["budgets"]["door_decoy"]["T"]

HEAD = """#!/bin/bash
# generated by src/gen/chain_jobs.py - organizer-side chain walks.
# Launch with the Appendix B.2 recipe (background jobs do not survive
# separate wsl.exe invocations):
#   Start-Process -FilePath wsl.exe -ArgumentList '-d','Ubuntu','--','bash',
#     '/home/ns8pc/jobs/chains_p6.sh' -WindowStyle Hidden
set -u
cd @ROOT@
RUNS=organizer-private/runs
CHAIN=src/chain/prambh_chain
mkdir -p /home/ns8pc/jobs
"""

TEMPLATE = """job_@NAME@() {
  local t0=$(date +%s)
  "$CHAIN" walk --seed-hex @SEED@ --s @S@ --t @T@ \\
      > /home/ns8pc/jobs/@NAME@.out 2> /home/ns8pc/jobs/@NAME@.err
  local rc=$?
  local t1=$(date +%s)
  python3 - "$RUNS/@REPORT@" "@NAME@" @SEED@ @S@ @T@ "$rc" "$((t1 - t0))" \\
      /home/ns8pc/jobs/@NAME@.out <<'PYEOF'
import sys
rep, name, seed, s, t, rc, secs, outfile = sys.argv[1:9]
out = open(outfile).read().strip()
lines = ["%s - organizer-side native chain walk" % name,
         "command: src/chain/prambh_chain walk --seed-hex %s --s %s --t %s"
         % (seed, s, t),
         "seed=%s" % seed, "S=%s T=%s" % (s, t), "out=%s" % out,
         "rc=%s elapsed_s=%s" % (rc, secs),
         "derived: ink=%s checkpoint=PRAMBH{%s} tail=%s"
         % (out[0:16], out[16:32], out[32:48])]
open(rep, "w").write("\\n".join(lines) + "\\n")
print("\\n".join(lines))
PYEOF
}
"""

TAIL = """
@CALLS@
wait
echo "chain jobs complete" >> /home/ns8pc/jobs/status.log
date -u +%Y-%m-%dT%H:%M:%SZ >> /home/ns8pc/jobs/status.log
touch /home/ns8pc/jobs/chainjobs.done
"""


def job(name, seed, s, t, report):
    return (TEMPLATE.replace("@NAME@", name).replace("@SEED@", seed)
            .replace("@S@", str(s)).replace("@T@", str(t))
            .replace("@REPORT@", report))


def emit(sets):
    body = HEAD.replace("@ROOT@", ROOT)
    calls = []
    if "loom1" in sets:
        body += job("chain1", mint.loom_seed_material(mint.capsule_content()).hex(),
                    S, T1, "chain1_walk.txt")
        calls.append("job_chain1 &")
    if "eyes2" in sets:
        body += job("chain2", mint.chain2_seed().hex(), S, T1, "chain2_walk.txt")
        calls.append("job_chain2 &")
    if "doors" in sets:
        for k in range(1, 8):
            body += job("door%d" % k, mint.door_decoy_vector(k).hex(), S, TDOOR,
                        "door%d_walk.txt" % k)
            calls.append("job_door%d &" % k)
    if "mirror" in sets:
        calls.append("python3 src/mirror/mirror_chain.py &")
    body += TAIL.replace("@CALLS@", "\n".join(calls))
    return body


def main(argv):
    sets = argv[1:] or ["loom1", "eyes2", "doors", "mirror"]
    known = {"loom1", "eyes2", "doors", "mirror", "all"}
    for s in sets:
        if s not in known:
            sys.stderr.write(__doc__)
            return 2
    if "all" in sets:
        sets = ["loom1", "eyes2", "doors", "mirror"]
    sys.stdout.write(emit(sets))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
