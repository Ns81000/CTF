#!/usr/bin/env python3
"""Generate src/core/canary.h from the minted canary token (spec 4.10).

Every shipped tool prints the canary on its usage screen, so every shipped
binary carries the token in .rodata.  The canary is a registered decoy
(TRAP_CATALOGUE.md, CANARY-1) and takes part in no derivation.

usage: gen_canary.py            (writes src/core/canary.h)
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, HERE)
import mint  # noqa: E402

TEMPLATE = """#ifndef PRAMBH_CANARY_H
#define PRAMBH_CANARY_H

/* generated by src/gen/gen_canary.py from the minted canary seed
 * (spec 4.10): printed on every shipped tool's usage screen.  The token
 * is a registered decoy and is used in no derivation. */
#define PRAMBH_CANARY "%s"

#endif
"""


def main():
    path = os.path.join(ROOT, "src", "core", "canary.h")
    with open(path, "w") as f:
        f.write(TEMPLATE % mint.canary_token())
    print("wrote %s (%s)" % (path, mint.canary_token()))


if __name__ == "__main__":
    main()
