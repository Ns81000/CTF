#!/usr/bin/env python3
"""gen_title_blob.py -- Phase 5 (Stage 4) internal mint + header generator.

Mints the assembled final flag from the three real components (the exact
recipe + real values are recorded in logs/PHASE_5_LOG.md only), asserts the
canonical flag format (PHASE_1_LOG D11), and writes:

  stage4_blob.h      kStage4ExpectedDigest[32] + CARTO_S4_EXPECTED_LEN
                     (D38 pattern: the tool holds a digest, never the
                     derivation) + kStage4DraftFlag[] (the struck
                     first-draft decoy shown in the solver-facing usage
                     text)
  stage4_layout.json internal machine-readable mirror (values only; the
                     seed strings stay in this file + the log)

The three inks (NEVER compiled into any binary; the suite asserts absence):
  engine ink  = bytes 16..23 of the Stage 1 real key material, as 16
                lowercase hex chars (NOT the Stage-1 token content, which
                is bytes 0..15 -- PHASE_2_LOG open question 2, decided)
  sheet ink   = the Stage 2 real reading, frame stripped
  oracle ink  = the Stage 3 master K = kA||kB, 16 lowercase hex chars

Decoy mint (reveals nothing about any real answer; own seed, D29 pattern;
the D50 lesson stands: no real component value is ever registered):
  "cartographer-ghost:stage4:decoy:first-draft:v1"

INTERNAL, not shipped. Deterministic; byte-reproducible.
"""
import hashlib
import json
import pathlib
import re

D11 = re.compile(r"^CARTO\{[a-z0-9_]{8,64}\}$")

# ---- the three real inks (sources of record: PHASE_2/3/4_LOGs) ----------
ENGINE_INK = "a5d66f1b2b5f596e"                # stage-1 real key bytes 16..23
SHEET_INK = "no_figure_sits_in_every_pixel"    # stage-2 reading, frame off
ORACLE_INK = "73070925a159f9e2"                # stage-3 master K = kA||kB

DECOY_SEED = "cartographer-ghost:stage4:decoy:first-draft:v1"

# ---- consistency anchors: the inks really are the transformations claimed
S1_KEY = "fd3e8049dfdfc32efe22fe823822b8c0a5d66f1b2b5f596e4c8111cf4224010f"
S2_READING = "CARTO{no_figure_sits_in_every_pixel}"
S1_TOKEN = "CARTO{fd3e8049dfdfc32efe22fe823822b8c0}"
assert S1_KEY[32:48] == ENGINE_INK
assert S1_KEY[:32] + "}" == S1_TOKEN[6:]  # the token content must NOT be reused
assert S2_READING[6:-1] == SHEET_INK

# ---- the assembly recipe (intended reading of the riddle) ---------------
# title = "CARTO{" ORACLE_INK "_" ENGINE_INK "_" SHEET_INK "}"
TITLE = "CARTO{%s_%s_%s}" % (ORACLE_INK, ENGINE_INK, SHEET_INK)
assert D11.match(TITLE), TITLE

decoy_contents = hashlib.sha256(DECOY_SEED.encode()).hexdigest()[:32]
DRAFT = "CARTO{%s}" % decoy_contents
assert D11.match(DRAFT) and DRAFT != TITLE

digest = hashlib.sha256(TITLE.encode()).digest()


def c_bytes(data):
    return ", ".join("0x%02x" % b for b in data)


def main():
    here = pathlib.Path(__file__).resolve().parent
    hdr = []
    hdr.append("/* GENERATED by gen_title_blob.py -- do not edit by hand.")
    hdr.append(" * INTERNAL build input (never shipped as source).")
    hdr.append(" * D38 pattern: the validator holds the expected flag only as a")
    hdr.append(" * SHA-256 digest + length; no component, no recipe, no flag.")
    hdr.append(" * Real values + recipe: logs/PHASE_5_LOG.md (internal only). */")
    hdr.append("#ifndef CARTO_STAGE4_BLOB_H")
    hdr.append("#define CARTO_STAGE4_BLOB_H")
    hdr.append("")
    hdr.append("#include <stdint.h>")
    hdr.append("")
    hdr.append("#define CARTO_S4_EXPECTED_LEN %du" % len(TITLE))
    hdr.append("")
    hdr.append("static const uint8_t kStage4ExpectedDigest[32] = {")
    rows = [digest[i:i + 8] for i in range(0, 32, 8)]
    for i, row in enumerate(rows):
        comma = "," if i < len(rows) - 1 else ""
        hdr.append("    %s%s" % (c_bytes(row), comma))
    hdr.append("};")
    hdr.append("")
    hdr.append("/* Struck first-draft decoy (solver-facing flavor text; also")
    hdr.append(" * registered in src/state/policy.h by policy_patch4.py).")
    hdr.append(" * Reveals nothing about any real answer (own seed; D29/D50). */")
    hdr.append('static const char kStage4DraftFlag[] = "%s";' % DRAFT)
    hdr.append("")
    hdr.append("#endif /* CARTO_STAGE4_BLOB_H */")
    (here / "stage4_blob.h").write_text("\n".join(hdr) + "\n")

    layout = {
        "title": TITLE,
        "title_len": len(TITLE),
        "digest": digest.hex(),
        "draft_flag": DRAFT,
        "decoy_seed": DECOY_SEED,
        "inks": {
            "engine": ENGINE_INK,
            "sheet": SHEET_INK,
            "oracle": ORACLE_INK,
        },
        "order": ["oracle", "engine", "sheet"],
        "separator": "_",
    }
    (here / "stage4_layout.json").write_text(json.dumps(layout, indent=2) + "\n")
    print("stage4_blob.h + stage4_layout.json written")
    print("title length:", len(TITLE))
    print("digest:", digest.hex())
    print("draft :", DRAFT)


if __name__ == "__main__":
    main()
