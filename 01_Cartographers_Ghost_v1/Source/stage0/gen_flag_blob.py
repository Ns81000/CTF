#!/usr/bin/env python3
r"""Generate flag_blob.h for stage0_start (Phase 1).

Internal build-time tool -- NOT shipped to solvers.

Canonical flag format (finalized Phase 1):
    ^CARTO{[a-z0-9_]{8,64}}$

Stage-0 real flag (ungated win, printed by stage0_start):
    CARTO{first_ink_in_the_ledger}

Obfuscation idiom (same family as the state-library HMAC key): the flag is
never stored plaintext in the binary. The mask is stored RAW -- no seed
string reaches the binary; derivation happens here at build time only.

    mask   = SHA-256("cartographer-flag-mask-stage0")
    stored = flag XOR mask (first len(flag) bytes)

Regenerate with:  python3 gen_flag_blob.py
(writes flag_blob.h next to this file)
"""

import hashlib
import pathlib
import re

FLAG = b"CARTO{first_ink_in_the_ledger}"
MASK_SEED = b"cartographer-flag-mask-stage0"


def main() -> None:
    if not re.fullmatch(r"CARTO\{[a-z0-9_]{8,64}\}", FLAG.decode()):
        raise SystemExit("minted flag violates the canonical flag format")

    mask = hashlib.sha256(MASK_SEED).digest()
    masked = bytes(a ^ b for a, b in zip(FLAG, mask))

    lines = []
    lines.append("/* flag_blob.h -- GENERATED by gen_flag_blob.py; do not edit by hand.")
    lines.append(" * Stage-0 real flag, XOR-masked. Constants recorded in logs/PHASE_1_LOG.md.")
    lines.append(" */")
    lines.append("#ifndef CARTO_FLAG_BLOB_H")
    lines.append("#define CARTO_FLAG_BLOB_H")
    lines.append("")
    lines.append("#define CARTO_S0_FLAG_LEN %du" % len(FLAG))
    lines.append("")
    lines.append("/* masked form of: %s */" % FLAG.decode())
    lines.append("static const unsigned char kCartoS0MaskedFlag[CARTO_S0_FLAG_LEN] = {")
    for i in range(0, len(masked), 8):
        chunk = masked[i:i + 8]
        lines.append("    " + ", ".join("0x%02x" % b for b in chunk) + ",")
    lines.append("};")
    lines.append("")
    lines.append("/* Raw 32-byte mask (build-time SHA-256 of an internal seed;")
    lines.append(" * the seed itself is never compiled into any binary). */")
    lines.append("static const unsigned char kCartoS0FlagMask[32] = {")
    for i in range(0, 32, 8):
        chunk = mask[i:i + 8]
        lines.append("    " + ", ".join("0x%02x" % b for b in chunk) + ",")
    lines.append("};")
    lines.append("")
    lines.append("#endif /* CARTO_FLAG_BLOB_H */")

    out = pathlib.Path(__file__).resolve().parent / "flag_blob.h"
    out.write_text("\n".join(lines) + "\n", newline="\n")
    print("wrote", out)


if __name__ == "__main__":
    main()
