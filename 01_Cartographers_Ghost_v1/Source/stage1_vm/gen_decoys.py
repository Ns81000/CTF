#!/usr/bin/env python3
r"""gen_decoys.py -- build-time generator for the Stage 1 decoy material.

INTERNAL build-time tool. NOT shipped to solvers.

Produces decoy_blob.h containing:
  * kStage1ForgottenKey[32] -- the ".rodata forgotten debug constant" decoy:
    a plausible-looking Stage 2 key that is WRONG. It is also the value the
    story implies a debugger-facing analysis would "recover".
  * kStage1ForgottenNote    -- the lure string that makes the constant look
    like a forgotten debug checkpoint.
The generator also prints the Stage 1 decoy flag minted from the constant
(registered in src/state/policy.h for decoy routing) and refuses to emit
anything that breaks the canonical flag format.

Regenerate with: python3 gen_decoys.py
"""

import hashlib
import pathlib
import re

DECOY_SEED = b"cartographer-ghost:stage1:decoy:forgotten-debug-key:v1"
NOTE = "stage2_key_checkpoint (pre-rekey) -- kept for the 0.4 survey; do not ship"


def main() -> None:
    key = hashlib.sha256(DECOY_SEED).digest()
    flag = "CARTO{%s}" % key[:16].hex()
    if not re.fullmatch(r"CARTO\{[a-z0-9_]{8,64}\}", flag):
        raise SystemExit("decoy flag violates the canonical flag format")

    lines = []
    lines.append("/* decoy_blob.h -- GENERATED by gen_decoys.py; do not edit.")
    lines.append(" * Stage 1 .rodata decoy: a plausible but WRONG Stage 2 key,")
    lines.append(" * presented as a forgotten debug checkpoint. Constants are")
    lines.append(" * recorded in logs/PHASE_2_LOG.md (internal).")
    lines.append(" */")
    lines.append("#ifndef CARTO_STAGE1_DECOY_BLOB_H")
    lines.append("#define CARTO_STAGE1_DECOY_BLOB_H")
    lines.append("")
    lines.append("#define CARTO_S1_DECOY_KEY_LEN 32u")
    lines.append("")
    lines.append("/* brace initialiser so the decoy record can embed the bytes inline */")
    lines.append("#define CARTO_S1_DECOY_KEY_INIT { \\")
    for i in range(0, 32, 8):
        row = "    " + ", ".join("0x%02x" % b for b in key[i:i + 8]) + ","
        if i < 24:
            lines.append(row + " \\")
        else:
            lines.append(row[:-1] + " }")
    lines.append("")
    lines.append("static const unsigned char kStage1ForgottenKey[CARTO_S1_DECOY_KEY_LEN] =")
    lines.append("    CARTO_S1_DECOY_KEY_INIT;")
    lines.append("")
    lines.append("static const char kStage1ForgottenNote[] =")
    lines.append('    "%s";' % NOTE)
    lines.append("")
    lines.append("#endif /* CARTO_STAGE1_DECOY_BLOB_H */")

    out = pathlib.Path(__file__).resolve().parent / "decoy_blob.h"
    out.write_text("\n".join(lines) + "\n", newline="\n")
    print("decoy key : " + key.hex())
    print("decoy flag: " + flag)
    print("wrote", out)


if __name__ == "__main__":
    main()
