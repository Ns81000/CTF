#!/usr/bin/env python3
"""Stage 4 seal generator -- deterministic on every run.

Mints everything the seal needs:

  seal_tables.h   the four shipped tables, the salts and the certificate
                  pairs.  These are public by design; this header goes to
                  the test-only MITM tool as well, which never sees a key.
  seal_blob.h     the closing key folded with a mask (only the folded form
                  is compiled into the shipped binary) and the older
                  construction's key, which is stamped in the open on
                  purpose (see --decoy).

The cipher is written here bit-exactly as the C build writes it, so the
certificate is minted once and never changes.
"""
import hashlib
import struct
import sys

CIPHER_SEED = "ghost2:stage4:cipher:v1"
KEY_SEED = "ghost2:stage4:key:v1"
MASK_SEED = "ghost2:mask:seal:v1"
DECOY_SEED = "ghost2:stage4:decoy:key:v1"

SALT = [0x243F6A88, 0x85A308D3, 0x13198A2E]

PLAINTEXTS = [
    bytes.fromhex("0001020304050607"),
    bytes.fromhex("0f0e0d0c0b0a0908"),
    bytes.fromhex("1122334455667788"),
    bytes.fromhex("a1b2c3d4e5f60718"),
]


def sha(b):
    return hashlib.sha256(b).digest()


def rotl(x, n):
    return ((x << n) | (x >> (32 - n))) & 0xFFFFFFFF


def make_tables():
    tables = []
    for ti in range(4):
        perm = list(range(256))
        pos = 0
        for i in range(255):
            block = sha(("%s:t%d:%d" % (CIPHER_SEED, ti, i)).encode())
            pos = (pos + block[0] + block[1]) % (256 - i)
            perm[i], perm[i + pos] = perm[i + pos], perm[i]
        tables.append(perm)
    return tables


def spread(a, tables):
    t = tables
    return (t[0][a & 0xFF] ^ t[1][(a >> 8) & 0xFF] ^
            (t[2][(a >> 16) & 0xFF] << 16) ^ (t[3][(a >> 24) & 0xFF] << 24))


def f_round(z, y, k, tables):
    return rotl(spread((y ^ k) & 0xFFFFFFFF, tables), 8 * z) ^ k ^ SALT[z]


def subkeys(key7):
    return [key7[0] | (key7[1] << 8) | (key7[2] << 16),
            key7[3],
            key7[4] | (key7[5] << 8) | (key7[6] << 16)]


def encrypt(block, key7, tables, order=(0, 1, 2)):
    ks = subkeys(key7)
    l = struct.unpack("<I", block[0:4])[0]
    r = struct.unpack("<I", block[4:8])[0]
    for z in order:
        new_r = l ^ f_round(z, r, ks[z], tables)
        l = r
        r = new_r
    return struct.pack("<I", l) + struct.pack("<I", r)


def emit_tables_header(tables, crows, path):
    """Tables + salts + certificate pairs: public by design, no key here."""
    lines = []
    lines.append("/* generated by gen_seal.py -- do not edit by hand */")
    lines.append("#ifndef CARTO_SEAL_TABLES_H")
    lines.append("#define CARTO_SEAL_TABLES_H")
    lines.append("")
    lines.append("#include <stdint.h>")
    lines.append("")
    lines.append("static const uint32_t kSalt[3] = {")
    lines.append("    0x%08xu, 0x%08xu, 0x%08xu" % tuple(SALT))
    lines.append("};")
    lines.append("")
    lines.append("static const uint8_t kT[4][256] = {")
    for ti in range(4):
        lines.append("    {")
        for j in range(0, 256, 16):
            lines.append("        " + " ".join("0x%02x," % b for b in tables[ti][j:j + 16]))
        lines.append("    },")
    lines.append("};")
    lines.append("")
    lines.append("/* the certificate pairs (public by design) */")
    lines.append("static const uint8_t kCertP[4][8] = {")
    for p in PLAINTEXTS:
        lines.append("    {" + " ".join("0x%02x," % b for b in p) + "},")
    lines.append("};")
    lines.append("static const uint8_t kCertC[4][8] = {")
    for c in crows:
        lines.append("    {" + " ".join("0x%02x," % b for b in c) + "},")
    lines.append("};")
    lines.append("")
    lines.append("#endif /* CARTO_SEAL_TABLES_H */")
    text = "\n".join(lines) + "\n"
    with open(path, "w", newline="\n") as fh:
        fh.write(text)
    return len(text)


def emit_blob_header(masked, decoy, path):
    lines = []
    lines.append("/* generated by gen_seal.py -- do not edit by hand */")
    lines.append("#ifndef CARTO_SEAL_BLOB_H")
    lines.append("#define CARTO_SEAL_BLOB_H")
    lines.append("")
    lines.append("#include <stdint.h>")
    lines.append("")
    lines.append('#define CARTO_SEAL_MASK_SEED "%s"' % MASK_SEED)
    lines.append("")
    lines.append("/* the closing key, folded with the mask above; the face of")
    lines.append(" * the stamp is public, the fold is not */")
    lines.append("static const uint8_t kMaskedKey[8] = {")
    lines.append("    " + " ".join("0x%02x," % b for b in masked))
    lines.append("};")
    lines.append("")
    lines.append("/* the older construction's key, stamped in the open on purpose */")
    lines.append("static const uint8_t kDecoyKey[8] = {")
    lines.append("    " + " ".join("0x%02x," % b for b in decoy))
    lines.append("};")
    lines.append("")
    lines.append("#endif /* CARTO_SEAL_BLOB_H */")
    text = "\n".join(lines) + "\n"
    with open(path, "w", newline="\n") as fh:
        fh.write(text)
    return len(text)


def main():
    tables = make_tables()
    key = sha(KEY_SEED.encode())[0:8]
    if key.hex() != "3821ad004ab30263":
        sys.exit("pinned seal key does not reproduce: %s" % key.hex())
    decoy = sha(DECOY_SEED.encode())[0:8]
    mask = sha(MASK_SEED.encode())[0:8]
    masked = bytes(a ^ b for a, b in zip(key, mask))

    crows = [encrypt(p, key[0:7], tables) for p in PLAINTEXTS]

    t_path = sys.argv[1] if len(sys.argv) > 1 else "seal_tables.h"
    b_path = sys.argv[2] if len(sys.argv) > 2 else "seal_blob.h"
    n1 = emit_tables_header(tables, crows, t_path)
    n2 = emit_blob_header(masked, decoy, b_path)

    print("seal key          %s" % key.hex())
    print("decoy key         %s" % decoy.hex())
    print("mask              %s" % mask.hex())
    for i in range(4):
        print("pair %d            %s -> %s"
              % (i + 1, PLAINTEXTS[i].hex(), crows[i].hex()))
    print("wrote %s (%d bytes), %s (%d bytes)" % (t_path, n1, b_path, n2))


if __name__ == "__main__":
    main()
