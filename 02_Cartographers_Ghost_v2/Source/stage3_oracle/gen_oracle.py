#!/usr/bin/env python3
"""Stage 3 generator: the oracle's fold tables and its masked seed.

Eight 256-byte tables (Z in {A,B}, j in 0..3).  Each table carries a planted
affine structure: exactly 64 of its entries W satisfy

    T[W] ^ T[W ^ (1 << b_Zj)] == W ^ W ^ (1 << b_Zj)

for that table's designated bit b_Zj.  The tables ship in the clear -- the
key does not.  The seed that the key is derived from ships masked, and the
mask can only be undone with the reading in hand.

  stage3_blob.h  -- the eight tables, the masked seed, and the tally
"""
import hashlib
import os
import sys

SEED_TABLE = "ghost2:stage3:table:v1"
SEED_REAL = hashlib.sha256(b"ghost2:stage3:seed:v1").digest()
READING = "CARTO{rust_blooms_under_tin_roofs}"
K_REAL = hashlib.sha256(SEED_REAL + READING.encode() +
                        bytes.fromhex("145e1d23feac3932")).digest()
K_COLD = hashlib.sha256(b"ghost2:stage3:cold:v1" + READING.encode()).digest()
ORACLE_INK = K_REAL[:8].hex()
COLD_INK = K_COLD[:8].hex()
TALLY_TOKEN = "CARTO{a_warm_plate_and_a_full_ring}"

BITS = {"A": (0, 1, 2, 3), "B": (5, 6, 7, 4)}
PLANTED_PAIRS = 32          # 32 pairs of 2 entries = 64 entries per table


def table(z, j):
    """One 256-byte table with a planted structure and exactly 64 entries
    that satisfy the affine relation for its bit."""
    raw = hashlib.sha256(("%s:%s:%d" % (SEED_TABLE, z, j)).encode()).digest()
    stream = b""
    key = raw
    while len(stream) < 1024:
        key = hashlib.sha256(key).digest()
        stream += key
    bit = 1 << BITS[z][j]
    t = bytearray(256)
    planted = set()
    # choose 32 pairs out of the 128 pairs that differ in that bit
    pairs = [w for w in range(256) if not (w & bit)]
    for idx, w in enumerate(pairs):
        if idx % 4 == 0:                       # exactly 32 of the 128 pairs
            t[w] = stream[idx]
            t[w | bit] = (t[w] ^ bit)
            planted.add(w)
            planted.add(w | bit)
        else:
            t[w] = stream[idx]
            # deliberately NOT the affine partner: bit b agrees with W's bit b
            partner = stream[idx + 512]
            t[w | bit] = (partner & ~bit) | (t[w] & bit)
    count = 0
    for w in range(256):
        if (t[w] ^ t[w ^ bit]) == bit:
            count += 1
    return bytes(t), count, len(planted)


def main():
    out_dir = os.path.dirname(os.path.abspath(__file__))
    tables = {}
    report = []
    for z in ("A", "B"):
        for j in range(4):
            t, count, planted = table(z, j)
            tables[(z, j)] = t
            report.append("T_%s_%d: %d entries satisfy the relation, "
                          "%d in planted pairs" % (z, j, count, planted))
            if count != 64:
                raise SystemExit("table %s%d has %d affine entries, want 64" %
                                 (z, j, count))
    mask_seed = ("ghost2:mask:oracle:seed:" + READING).encode()
    mask = hashlib.sha256(mask_seed).digest()
    masked_seed = bytes(a ^ b for a, b in zip(SEED_REAL, mask))

    parts = ["/* generated by gen_oracle.py -- do not edit by hand */",
             "#ifndef CARTO_STAGE3_BLOB_H",
             "#define CARTO_STAGE3_BLOB_H", "", "#include <stdint.h>", ""]
    parts.append("static const uint8_t kT[8][256] = {")
    for z in ("A", "B"):
        for j in range(4):
            t = tables[(z, j)]
            parts.append("  {")
            for i in range(0, 256, 16):
                parts.append("    " + " ".join("0x%02x," % b
                                               for b in t[i:i + 16]))
            parts.append("  },")
    parts.append("};")
    parts.append("")
    parts.append("static const uint8_t kMaskedSeed[32] = {")
    for i in range(0, 32, 4):
        parts.append("    " + " ".join("0x%02x," % b
                                       for b in masked_seed[i:i + 4]))
    parts.append("};")
    parts.append("")
    parts.append('static const char kTallyToken[] = "%s";' % TALLY_TOKEN)
    parts.append("")
    parts.append("#endif /* CARTO_STAGE3_BLOB_H */")
    with open(os.path.join(out_dir, "stage3_blob.h"), "w", newline="\n") as fh:
        fh.write("\n".join(parts) + "\n")

    # the model reads the tables and the masked seed from here
    import json
    with open(os.path.join(out_dir, "stage3_tables.json"), "w",
              newline="\n") as fh:
        json.dump({"tables": [list(tables[("A", j)]) for j in range(4)] +
                              [list(tables[("B", j)]) for j in range(4)],
                   "masked_seed": list(masked_seed),
                   "bits": {"A": list(BITS["A"]), "B": list(BITS["B"])},
                   "k_real": K_REAL.hex(), "k_cold": K_COLD.hex(),
                   "reading": READING}, fh, indent=1)
        fh.write("\n")

    for line in report:
        print(line)
    print("oracle ink  %s  (K_real[0:8], never printed by the tool)" % ORACLE_INK)
    print("cold ink    %s  (what the static path yields)" % COLD_INK)
    print("kA %s kB %s (little-endian halves)"
          % (K_REAL[:4][::-1].hex(), K_REAL[4:8][::-1].hex()))
    return 0


if __name__ == "__main__":
    sys.exit(main())
