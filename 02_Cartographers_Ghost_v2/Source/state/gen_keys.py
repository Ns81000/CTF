#!/usr/bin/env python3
"""Deterministic generator for the state library's masked key blob.

  master = SHA-256("ghost2:master:v2")
  mask   = SHA-256("ghost2:mask:master:v2")
  blob   = master XOR mask

Only the masked blob is ever compiled in; the plaintext master exists solely
in stack buffers at run time.  Every tool shares this one handshake because a
single state record has to be readable by all of them (see KEYS_V2.md).
"""
import hashlib
import sys

MASTER_SEED = "ghost2:master:v2"
MASK_SEED = "ghost2:mask:master:v2"


def sha_hex(s):
    return hashlib.sha256(s.encode()).hexdigest()


def main():
    master = bytes.fromhex(sha_hex(MASTER_SEED))
    mask = bytes.fromhex(sha_hex(MASK_SEED))
    blob = bytes(a ^ b for a, b in zip(master, mask))

    lines = []
    lines.append("/* generated by gen_keys.py -- do not edit by hand */")
    lines.append("#ifndef CARTO_KEYS_BLOB_H")
    lines.append("#define CARTO_KEYS_BLOB_H")
    lines.append("")
    lines.append("#include <stdint.h>")
    lines.append("")
    lines.append("/* mask seed used to reverse the blob below (a compile-time")
    lines.append(" * constant, not a secret; see KEYS_V2.md for the reasoning) */")
    lines.append('#define CARTO_MASTER_MASK_SEED "%s"' % MASK_SEED)
    lines.append("")
    lines.append("/* master XOR SHA-256(CARTO_MASTER_MASK_SEED) */")
    lines.append("static const uint8_t kMaskedMaster[32] = {")
    for i in range(0, 32, 4):
        lines.append("    " + " ".join("0x%02x," % b for b in blob[i:i + 4]))
    lines.append("};")
    lines.append("")
    lines.append("#endif /* CARTO_KEYS_BLOB_H */")
    text = "\n".join(lines) + "\n"

    out = sys.argv[1] if len(sys.argv) > 1 else "keys_blob.h"
    with open(out, "w", newline="\n") as fh:
        fh.write(text)

    # Echo the values an organiser needs; none of these are shipped.
    print("master            %s" % master.hex())
    print("K_state           %s" % sha_hex(MASTER_SEED + "|" + "ghost2:state"))
    for i in range(6):
        k = hashlib.sha256(master + ("ghost2:stage:%d" % i).encode()).hexdigest()
        print("K_stage_%d         %s" % (i, k))
    print("wrote %s (%d bytes)" % (out, len(text)))


if __name__ == "__main__":
    main()
